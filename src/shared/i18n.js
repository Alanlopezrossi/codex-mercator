export function pagePath(lang, page) {
  const slug = ROUTES[page][lang];
  return slug ? `/${lang}/${slug}` : `/${lang}/`;
}

export function slugify(s) {
  return String(s || '')
    .normalize('NFD')
    .replace(/[̀-ͯ]/g, '')
    .toLowerCase()
    .replace(/[^a-z0-9]+/g, '-')
    .replace(/^-+|-+$/g, '')
    .slice(0, 80);
}

export function itemPath(lang, id, name) {
  const s = slugify(name);
  return `/${lang}/item/${id}${s ? `-${s}` : ''}`;
}

