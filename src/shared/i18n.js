function human(s) {
  return String(s || '').replace(/([a-z])([A-Z])/g, '$1 $2').replace(/^./, (c) => c.toUpperCase());
}
function humanLower(s) {
  const h = human(s);
  return h.charAt(0) + h.slice(1).toLowerCase();
}

